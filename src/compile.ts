// Compile: project the resolved model into derived, gitignorable files. Never touches git, never writes outside <root>/.dt.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DtError } from './types.ts';
import type { Collection, Field, Model } from './types.ts';

const ENGINE = fileURLToPath(new URL('../bin/dt.ts', import.meta.url));

function describe(name: string, f: Field): string {
  const kind = f.enum ? f.enum.join('|')
    : typeof f.type !== 'string' ? `→ ${f.type.join('|')}`
    : ['string', 'markdown', 'url', 'email', 'date', 'datetime', 'integer', 'number', 'boolean', 'object', 'map', 'position'].includes(f.type) ? f.type
    : f.type === 'reference' ? '→ any collection' : `→ ${f.type}`;
  return `${name}${f.required ? '*' : ''}${f.many ? '[]' : ''}: ${kind}${f.default !== undefined ? ` (default ${f.default})` : ''}`;
}

function entry(c: Collection): string[] {
  const body = Object.keys(c.fields).find((n) => c.fields[n].body);
  const fields = Object.entries(c.fields).filter(([n, f]) => !f.mirror_of && n !== body).map(([n, f]) => describe(n, f));
  const file = c.storage.shape === 'folder' ? `<id>/${c.storage.entry ?? 'index.md'}` : `<id>.${c.storage.suffix}.${c.storage.format}`;
  return [
    `- **${c.name}** (${c.module}) — ${c.description ?? ''}`.trimEnd(),
    ...(c.use_when ? [`  use when: ${c.use_when}`] : []),
    `  records: ${c.storage.path}/${file} · id from ${c.ids.from.map((t) => `\`${t}\``).join(', else ')}`,
    `  fields: ${fields.join(' · ')}${body ? ` · ${body}: the text below the frontmatter` : ''}`,
  ];
}

export function instructions(model: Model): string {
  const lines = ['# Workspace instructions (generated by compile — do not edit)', '',
    'Records are plain files, and a reference to one is `<collection>/<id>`. Change them through the engine, which validates before it writes:', '',
    `    node ${ENGINE} <verb> …        (written \`dt\` below)`, '',
    '- `dt list <collection> [--filter field=value]` · `dt get <ref>` · `dt add <collection> ["title"] --field value …` · `dt set <ref> field=value …` · `dt rm <ref>` · `dt check`',
    '- In the field lists, `*` marks a required field and `[]` a list: repeat the flag, or separate the values with commas. `→` marks a reference to a record of that collection.', '',
    '## Collections', ''];
  for (const c of Object.values(model.collections).sort((a, b) => a.name.localeCompare(b.name))) lines.push(...entry(c));
  lines.push('', '## Skills', '');
  for (const s of model.skills) lines.push(`- **${s.name}** (${s.module}) — ${s.description} Read \`${relative(model.root, s.path)}\`.`);
  return lines.join('\n') + '\n';
}

export function compile(model: Model): string[] {
  const errors = model.issues.filter((i) => i.severity === 'error');
  if (errors.length) throw new DtError('the workspace model has errors — nothing compiled; fix them first', errors);
  const out = join(model.root, '.dt');
  mkdirSync(out, { recursive: true });
  // paths are written relative to the workspace, so the model is the same wherever the workspace is checked out
  const portable = { ...model, root: '.', modules: model.modules.map((m) => ({ ...m, dir: relative(model.root, m.dir) })), skills: model.skills.map((s) => ({ ...s, path: relative(model.root, s.path) })) };
  const files: Record<string, string> = {
    'model.json': JSON.stringify(portable, null, 2) + '\n',
    'AGENTS.md': instructions(model),
    '.gitignore': '*\n',
  };
  for (const [name, text] of Object.entries(files)) writeFileSync(join(out, name), text);
  return Object.keys(files).map((n) => join(out, n));
}
