import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, rmdirSync, writeFileSync } from "node:fs"
import { basename, dirname, join, relative, sep } from "node:path"
import { Document, isScalar, parse, visit } from "yaml"
import { asObject } from "../lib/asObject.ts"
import { asOptional } from "../lib/asOptional.ts"
import { asNames } from "../lib/asNames.ts"
import { listFiles } from "../lib/listFiles.ts"
import type { Model } from "../types/Model.ts"
import { orientation } from "./orientation.ts"

/** the released engine's markers, byte for byte: tools that merge branches recognise generated text by them */
export const STAMP =
  "<!-- generated by dreamteamer compile — do not edit; source of truth lives in modules/<module>/<kind>/ -->"
const BLOCKS = [
  ["<!-- dreamteamer:begin (generated — do not edit inside this block) -->", "<!-- dreamteamer:end -->"],
  ["<!-- dreamteamer:instructions:begin -->", "<!-- dreamteamer:instructions:end -->"],
]

function stamped(text: string) {
  return text.includes(STAMP) ? text : `${text.trimEnd()}\n\n${STAMP}\n`
}

/** an agent as a claude-code subagent: `skills` is no harness key, so it becomes the body's first instruction */
function agent(file: string) {
  const text = readFileSync(file, "utf8")
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text)
  if (!m) return text
  const doc = asObject(parse(m[1]) ?? {}, file)
  const skills = (asOptional(doc.skills, `${file}: skills`, asNames) ?? []).map((t) => t.replace(/^skills\//, ""))
  delete doc.skills
  const load = skills.length ? `ALWAYS load these skills (Skill tool) before acting: ${skills.join(", ")}.\n\n` : ""
  // as js-yaml dumps it: a string longer than a line is folded as a block
  const yaml = new Document(doc)
  visit(yaml, (_, n) => {
    if (isScalar(n) && typeof n.value === "string" && n.value.length > 120) n.type = "BLOCK_FOLDED"
  })
  return `---\n${yaml.toString({ lineWidth: 120 })}---\n\n${load}${text.slice(m[0].length).trimStart()}`
}

/** a user-owned root file with the managed blocks in front of the rest; no blocks removes them, and an emptied file */
function rootFile(file: string, blocks: string[] | undefined) {
  let text = existsSync(file) ? readFileSync(file, "utf8") : ""
  if (!blocks && !BLOCKS.some(([b]) => text.includes(b))) return
  for (const [b, e] of BLOCKS) {
    const i = text.indexOf(b)
    const j = text.indexOf(e, i)
    if (i >= 0 && j >= 0)
      text = `${text.slice(0, i).replace(/\n{0,2}$/, "")}\n${text.slice(j + e.length).replace(/^\n/, "")}`
  }
  const rest = text.replace(/^\s+/, "")
  if (blocks) writeFileSync(file, `${blocks.join("\n\n")}\n${rest ? `\n${rest}` : ""}`)
  else if (rest) writeFileSync(file, rest)
  else rmSync(file)
}

/**
 * Deliver what the modules ship to claude-code, as the released engine does: each skill's folder, agent and command
 * under `.claude/`, and in `CLAUDE.md` the orientation block followed by `DREAMTEAMER.md`, the workspace's own rules,
 * verbatim, under the system module's version. A file a previous delivery wrote (`prev`) that this one did not is
 * removed; with claude-code not named, the blocks go too. Returns what it wrote. Review: codex, pi, gemini-cli and
 * cursor are not delivered to, and another name is skipped without a word.
 */
export function deliver(model: Model, harnesses: string[], prev: string[]): string[] {
  const out: string[] = []
  function write(rel: string, body: string | Buffer) {
    mkdirSync(dirname(join(model.root, rel)), { recursive: true })
    writeFileSync(join(model.root, rel), body)
    out.push(rel)
  }
  const on = harnesses.includes("claude-code")
  for (const [id, entry] of Object.entries(on ? model.sources.skills : {}))
    for (const f of listFiles(dirname(entry))) {
      const rel = `.claude/skills/${id}/${relative(dirname(entry), f).split(sep).join("/")}`
      write(rel, rel.endsWith(".md") ? stamped(readFileSync(f, "utf8")) : readFileSync(f))
    }
  for (const [id, f] of Object.entries(on ? model.sources.agents : {}))
    write(`.claude/agents/${basename(id)}.md`, stamped(agent(f)))
  for (const [id, f] of Object.entries(on ? model.sources.commands : {}))
    write(`.claude/commands/${id}.md`, stamped(readFileSync(f, "utf8")))
  const own = join(model.root, "DREAMTEAMER.md")
  const rules = existsSync(own) ? readFileSync(own, "utf8").trimEnd() : ""
  const blocks = [[BLOCKS[0], orientation(model, model.modules[0].version)] as const, [BLOCKS[1], rules] as const]
  const wrapped = blocks.filter(([, t]) => t).map(([[b, e], t]) => `${b}\n${t}\n${e}`)
  rootFile(join(model.root, "CLAUDE.md"), on ? wrapped : undefined)
  // a file the last delivery wrote and this one did not goes, and so do the folders it leaves empty
  for (const t of prev.filter((p) => !out.includes(p) && p.startsWith(".claude/") && !p.split("/").includes(".."))) {
    rmSync(join(model.root, t), { force: true })
    for (let d = dirname(t); d !== "." && existsSync(join(model.root, d)); d = dirname(d))
      if (!readdirSync(join(model.root, d)).length) rmdirSync(join(model.root, d))
  }
  return out
}
