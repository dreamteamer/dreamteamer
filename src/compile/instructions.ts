import { relative } from "node:path"
import { fileURLToPath } from "node:url"
import { bodyField } from "../model/bodyField.ts"
import { tail } from "../store/tail.ts"
import type { Collection } from "../types/Collection.ts"
import type { Field } from "../types/Field.ts"
import type { Model } from "../types/Model.ts"

const ENGINE = fileURLToPath(new URL("../../bin/dt.ts", import.meta.url))
const PLAIN = [
  "string",
  "markdown",
  "url",
  "email",
  "date",
  "datetime",
  "integer",
  "number",
  "boolean",
  "object",
  "map",
  "position",
]

function describe(name: string, f: Field) {
  const kind = f.enum
    ? f.enum.join("|")
    : typeof f.type !== "string"
      ? `→ ${f.type.join("|")}`
      : PLAIN.includes(f.type)
        ? f.type
        : f.type === "reference"
          ? "→ any collection"
          : `→ ${f.type}`
  // eslint-disable-next-line @typescript-eslint/no-base-to-string -- a default is shown as a template writes it
  const given = f.default !== undefined ? ` (default ${String(f.default)})` : ""
  return `${name}${f.required ? "*" : ""}${f.many ? "[]" : ""}: ${kind}${given}`
}

function entry(c: Collection, source: boolean) {
  const body = bodyField(c)
  const fields = Object.entries(c.fields)
    .filter(([n, f]) => !f.mirror_of && n !== body)
    .map(([n, f]) => describe(n, f))
  return [
    `- **${c.name}** (${c.module}) — ${c.description ?? ""}`.trimEnd(),
    ...(c.use_when ? [`  use when: ${c.use_when}`] : []),
    source
      ? `  records: read-only here — the files each module ships in its ${c.storage.path}/ folder`
      : `  records: ${c.storage.path}/<id>${tail(c)} · id from ${c.ids.from.map((t) => `\`${t}\``).join(", else ")}`,
    `  fields: ${fields.join(" · ")}${body ? ` · ${body}: the text below the frontmatter` : ""}`,
  ]
}

/** The workspace's schema as instructions an agent can read: how to run the engine, every collection and skill. */
export function instructions(model: Model): string {
  const lines = [
    "# Workspace instructions (generated by compile — do not edit)",
    "",
    "Records are plain files, and a reference to one is `<collection>/<id>`. Change them through the engine, which validates before it writes:",
    "",
    `    node ${ENGINE} <verb> …        (written \`dt\` below)`,
    "",
    '- `dt list <collection> [--filter field=value]` · `dt get <ref>` · `dt add <collection> ["title"] --field value …` · `dt set <ref> field=value …` · `dt rm <ref>` · `dt check`',
    "- In the field lists, `*` marks a required field and `[]` a list: separate the values with commas, or repeat the flag to give each value whole, commas and all. `→` marks a reference to a record of that collection.",
    "",
    "## Collections",
    "",
  ]
  for (const c of Object.values(model.collections).sort((a, b) => a.name.localeCompare(b.name)))
    lines.push(...entry(c, Boolean(model.sources[c.name])))
  lines.push("", "## Skills", "")
  // a skill outside the workspace, such as the engine's own, is named by its full path
  for (const s of model.skills) {
    const at = relative(model.root, s.path).startsWith("..") ? s.path : relative(model.root, s.path)
    lines.push(`- **${s.name}** (${s.module}) — ${s.description} Read \`${at}\`.`)
  }
  return lines.join("\n") + "\n"
}
